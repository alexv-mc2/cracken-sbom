"""Generate detect_globs_gen.go from the pinned Syft's cataloger capabilities.

Syft v1.55.0 has no `syft cataloger info` command; `syft cataloger list -o json`
prints names and tags only. The file patterns live in the capability files of
the Syft source tree (syft/pkg/cataloger/*/capabilities.yaml, Apache-2.0,
Anchore, Inc.). This script reads them from a local checkout of the exact
pinned tag and writes the Go table detect uses, so detection matches what the
engine will catalog.

Usage (release time, after a Syft bump; needs network only for the clone):

    git clone --depth 1 --branch v1.55.0 https://github.com/anchore/syft.git /tmp/syft-src
    python3 scripts/gen-detect-globs.py /tmp/syft-src > detect_globs_gen.go
    gofmt -l detect_globs_gen.go   # must print nothing

The tag must equal engineVersion in engine.go; the script refuses otherwise.
Only the Python standard library is used; the YAML subset Syft writes for these
files (block lists and scalars, generated by its own tool) is read line by line.
"""
import re
import subprocess
import sys
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent.parent


def engine_version():
    text = (TOOL_DIR / "engine.go").read_text()
    match = re.search(r'const engineVersion = "([0-9.]+)"', text)
    if not match:
        sys.exit("engineVersion not found in engine.go")
    return match.group(1)


def checkout_tag(src):
    try:
        out = subprocess.run(["git", "-C", str(src), "describe", "--tags", "--exact-match"],
                             check=True, capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        sys.exit("the Syft source must be a git checkout of an exact release tag")
    return out


def scalar(value):
    value = re.sub(r"\s+#.*$", "", value).strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        value = value[1:-1]
    return value


def expand_braces(pattern):
    match = re.search(r"\{([^{}]*)\}", pattern)
    if not match:
        return [pattern]
    out = []
    for choice in match.group(1).split(","):
        out.extend(expand_braces(pattern[:match.start()] + choice + pattern[match.end():]))
    return out


def parse_catalogers(path):
    """Yield (ecosystem, name, selectors, [glob, ...]) for one capabilities file."""
    lines = path.read_text().splitlines()
    blocks, current = [], None
    for line in lines:
        if re.match(r"^  - ecosystem:", line):
            current = [line]
            blocks.append(current)
        elif current is not None:
            if line and not line.startswith(" "):
                current = None
            else:
                current.append(line)
    for block in blocks:
        ecosystem = scalar(block[0].split(":", 1)[1])
        name, selectors, globs = "", [], []
        i = 0
        while i < len(block):
            line = block[i]
            stripped = line.strip()
            indent = len(line) - len(line.lstrip())
            if indent == 4 and stripped.startswith("name:"):
                name = scalar(stripped.split(":", 1)[1])
            elif indent == 4 and stripped.startswith("selectors:"):
                i += 1
                while i < len(block) and block[i].strip().startswith("- ") and len(block[i]) - len(block[i].lstrip()) > 4:
                    selectors.append(scalar(block[i].strip()[2:]))
                    i += 1
                continue
            elif re.match(r"^(- )?method:", stripped) and scalar(stripped.split(":", 1)[1]) == "glob":
                j = i + 1
                while j < len(block) and not block[j].strip().startswith("criteria:"):
                    j += 1
                if j < len(block):
                    crit_indent = len(block[j]) - len(block[j].lstrip())
                    k = j + 1
                    while k < len(block):
                        item = block[k]
                        if not item.strip().startswith("- ") or len(item) - len(item.lstrip()) < crit_indent:
                            break
                        globs.extend(expand_braces(scalar(item.strip()[2:])))
                        k += 1
                    i = k
                    continue
            i += 1
        if name and globs:
            yield ecosystem, name, selectors, globs


def kind(selectors):
    """globOS: an operating-system package database (a root filesystem);
    globDeclared: a project manifest or lockfile; globInstalled: installed
    language packages; globOther: binaries and archives (not used to choose)."""
    if "binary" in selectors:
        return "globOther"
    if "os" in selectors:
        return "globOS"
    if "declared" in selectors:
        return "globDeclared"
    if "installed" in selectors:
        return "globInstalled"
    return "globOther"


def go_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-detect-globs.py /path/to/syft-source-checkout")
    src = Path(sys.argv[1]).resolve()
    version = engine_version()
    tag = checkout_tag(src)
    if tag != "v" + version:
        sys.exit(f"Syft source is at {tag}, but engine.go pins {version}")
    rows = set()
    files = sorted((src / "syft" / "pkg" / "cataloger").glob("*/capabilities.yaml"))
    if not files:
        sys.exit("no syft/pkg/cataloger/*/capabilities.yaml files found")
    for path in files:
        for ecosystem, name, selectors, globs in parse_catalogers(path):
            if "directory" not in selectors:
                continue  # detect only looks at local folders and files.
            for glob in globs:
                rows.add((ecosystem, name, kind(selectors), glob))
    if not rows:
        sys.exit("no glob patterns found")
    out = [
        "// Code generated by scripts/gen-detect-globs.py from Syft v" + version + "; DO NOT EDIT.",
        "//",
        "// Source: syft/pkg/cataloger/*/capabilities.yaml at github.com/anchore/syft",
        "// tag v" + version + " (Copyright Anchore, Inc., Apache-2.0). Only catalogers",
        "// that run on directory scans are listed. Regenerate after every Syft bump.",
        "",
        "package main",
        "",
        "// detectGlobsSyftVersion must equal engineVersion (checked by detect_test.go).",
        "const detectGlobsSyftVersion = " + go_string(version),
        "",
        "var detectGlobs = []detectGlob{",
    ]
    for ecosystem, name, k, glob in sorted(rows):
        out.append("\t{" + ", ".join([go_string(ecosystem), go_string(name), k, go_string(glob)]) + "},")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
